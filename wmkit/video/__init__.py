"""视频水印清理。

为什么视频比图片难
------------------
图片是单帧，修好就算完。视频多了一个维度上的约束：**时序一致性**。
逐帧独立修复会让原本静止的水印处"忽明忽暗"地闪 —— 实测下来，
逐帧 inpaint 的帧间抖动（0.42）比不处理时的水印本身（0.25）还大，
也就是"修完比不修更难看"。所以本模块固定包含一道**时域稳定**工序。

路线选择（本机无 NVIDIA GPU，故不走模型方案）
    · alpha 反算：单帧上极准，但要求 alpha 很准；估偏时误差反而更大
      （实测 31.11 vs inpaint 的 1.48）—— 视频里通常不知道 alpha，故不设默认
    · OpenCV inpaint + 时域中值：不依赖 alpha，实测误差 1.47、抖动 0.21
      ★ 本模块默认走这条
    · ProPainter 类模型：效果最好但需 GPU，留作将来扩展

模块划分
    io.py       ffmpeg 管道读写（保留音轨）
    probe.py    定位水印：找"整段视频里几乎不变"的区域
    process.py  逐帧修复 + 时域稳定
    cli.py      命令行
"""
__all__ = ["io", "probe", "process", "cli"]
